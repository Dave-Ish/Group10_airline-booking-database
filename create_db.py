cur.execute("CREATE TABLE IF NOT EXISTS bookings (booking_id INTEGER PRIMARY KEY AUTOINCREMENT, passenger_id INTEGER, current_location TEXT, destination TEXT, class_tier TEXT, seat_preference TEXT, lounge_pass_code TEXT, suite_number TEXT, chauffeur_service TEXT, FOREIGN KEY(passenger_id) REFERENCES passengers(passenger_id))")
